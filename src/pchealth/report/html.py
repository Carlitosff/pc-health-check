def _esc(value: object) -> str:
    return html.escape(str(value))


def _grade_color(grade: str) -> str:
    return _GRADE_COLORS.get(grade, "#6b7178")


def _document(title: str, body: str) -> str:
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n<head>\n'
        '<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{_esc(title)}</title>\n"
        f"<style>{_STYLE}</style>\n"
        "</head>\n<body>\n"
        f'<div class="wrap">\n{body}\n</div>\n'
        "</body>\n</html>\n"
    )


def _component_rows(components: List[ComponentScore]) -> str:
    rows = []
    for c in components:
        if not c.available:
            rows.append(
                "<tr>"
                f"<td>{_esc(c.name)}</td>"
                '<td><span class="na">n/a</span></td>'
                '<td class="num na">-</td>'
                '<td class="num na">-</td>'
                f'<td class="na">{_esc(c.summary)}</td>'
                "</tr>"
            )
            continue
        color = _grade_color(c.grade)
        weight = f"{c.weight * 100:.0f}%" if c.weight else "-"
        rows.append(
            "<tr>"
            f"<td>{_esc(c.name)}</td>"
            f'<td><span class="pill" style="background:{color}">{_esc(c.grade)}</span></td>'
            f'<td class="num">{c.score:.0f}</td>'
            f'<td class="num">{weight}</td>'
            f"<td>{_esc(c.summary)}</td>"
            "</tr>"
        )
    return "\n".join(rows)


def render_report_html(report: HealthReport) -> str:
    color = _grade_color(report.overall_grade)
    body = f"""
<h1>PC Health Check</h1>
<div class="meta">
  <span><strong>Host:</strong> {_esc(report.hostname or "unknown")}</span>
  <span><strong>Platform:</strong> {_esc(report.platform)}</span>
  <span><strong>Generated:</strong> {_esc(report.generated_at)}</span>
</div>
<div class="hero">
  <div class="grade-badge" style="background:{color}">{_esc(report.overall_grade)}</div>
  <div class="hero-score">
    Overall health<br>
    <strong>{report.overall_score:.0f}</strong> / 100
  </div>
</div>
<table>
  <thead>
    <tr>
      <th>Component</th><th>Grade</th>
      <th class="num">Score</th><th class="num">Weight</th><th>Details</th>
    </tr>
  </thead>
  <tbody>
{_component_rows(report.components)}
  </tbody>
</table>
<footer>Generated by pc-health-check v{_esc(report.tool_version)}</footer>
"""
    return _document(f"PC Health Check - {report.hostname or 'report'}", body)


def _entry_rows(entries: List[FileEntry], total: int) -> str:
    rows = []
    biggest = max((e.size_bytes for e in entries), default=0) or 1
    for index, entry in enumerate(entries, start=1):
        share = entry.size_bytes / total * 100 if total else 0
        bar_pct = entry.size_bytes / biggest * 100
        rows.append(
            "<tr>"
            f'<td class="num na">{index}</td>'
            f'<td class="num">{_esc(human_size(entry.size_bytes))}</td>'
            f'<td class="num na">{share:.1f}%</td>'
            f'<td><div class="bar"><span style="width:{bar_pct:.1f}%;'
            'background:#4c8bf5"></span></div></td>'
            f'<td class="path">{_esc(entry.path)}</td>'
            "</tr>"
        )
    return "\n".join(rows)


def _entries_section(title: str, entries: List[FileEntry], total: int) -> str:
    if not entries:
        return ""
    return f"""
<h2>{_esc(title)}</h2>
<table>
  <thead>
    <tr><th class="num">#</th><th class="num">Size</th><th class="num">Share</th>
    <th></th><th>Path</th></tr>
  </thead>
  <tbody>
{_entry_rows(entries, total)}
  </tbody>
</table>
"""


def render_scan_html(result: ScanResult) -> str:
    body = f"""
<h1>Heavy File Scan</h1>
<div class="meta">
  <span class="path"><strong>Root:</strong> {_esc(result.root)}</span>
  <span><strong>Files:</strong> {result.files_scanned:,}</span>
  <span><strong>Total:</strong> {_esc(human_size(result.total_bytes))}</span>
  {"<span><strong>Unreadable:</strong> %d</span>" % result.errors if result.errors else ""}
</div>
{_entries_section("Heaviest folders", result.top_dirs, result.total_bytes)}
{_entries_section("Heaviest files", result.top_files, result.total_bytes)}
"""
    return _document("Heavy File Scan", body)


def write_html_report(report: HealthReport, path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(render_report_html(report))


def write_html_scan(result: ScanResult, path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(render_scan_html(result))
